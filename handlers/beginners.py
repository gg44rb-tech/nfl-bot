@router.callback_query(F.data == "beginners_faq")
async def beginners_faq(callback: CallbackQuery):
    text = """
❓ <b>Часто задаваемые вопросы</b>

<b>С какого возраста можно играть?</b>
Взрослые команды берут с 16-18 лет. Есть детские лиги с 8 лет и юношеские до 18 лет.

<b>Нужна ли физическая подготовка?</b>
Базовая форма желательна, но команды берут всех. Главное — желание учиться. Тренеры сами подготовят физически.

<b>Опасно ли это?</b>
При правильной экипировке и технике — не опаснее хоккея или борьбы. Большинство травм — растяжения, не переломы.

<b>Сколько стоит заниматься?</b>
Командный взнос 3-8 тыс/сезон + экипировка ~15 тыс (один раз). Итого ~20-25 тыс для старта — доступно!

<b>Можно ли играть девушкам?</b>
Да! Есть смешанные команды и женские лиги. Флаг-футбол особенно популярен среди женщин.

<b>Сколько времени занимает?</b>
2-3 тренировки в неделю (по 2 часа) + игры по выходным в сезон (апрель-август).

<b>Нужно ли знать английский?</b>
Желательно на базовом уровне — многие термины английские. Но в российских командах всё объясняют по-русски.

<b>Как смотреть NFL в России?</b>
• NFL Game Pass (официальный стриминг)
• YouTube — нарезки и обзоры
• Telegram каналы об NFL на русском языке

<b>Есть ли американский футбол в моём городе?</b>
Скорее всего да! Используй раздел "Найти команду" в боте 🏈
"""
    await callback.message.edit_text(text, reply_markup=back_kb("menu_beginners"))
