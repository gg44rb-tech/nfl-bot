from aiogram import Router, F
from aiogram.types import CallbackQuery
from keyboards.menus import beginners_kb, back_kb

router = Router()


@router.callback_query(F.data == "beginners_start")
async def beginners_start(callback: CallbackQuery):
    text = """
🚀 <b>С чего начать в американском футболе?</b>

<b>Шаг 1 — Изучи базу</b>
Начни с раздела "База знаний" в этом боте. Пойми правила, позиции и терминологию. Без этого будет сложно на первой тренировке.

<b>Шаг 2 — Попробуй флаг-футбол</b>
Флаг-футбол — бесконтактная версия. Отличный старт без дорогой экипировки и риска травм. Многие команды проводят флаг-турниры.

<b>Шаг 3 — Найди команду</b>
Большинство команд рады новичкам без опыта! Приходи на открытую тренировку — тренеры оценят твои данные и подберут позицию.

<b>Шаг 4 — Купи базовую экипировку</b>
Для начала нужны только капа (защита зубов) и удобная спортивная одежда. Полную экипировку можно взять у команды или купить позже.

<b>Шаг 5 — Тренируйся регулярно</b>
2-3 тренировки в неделю. Американский футбол — командный спорт, пропуски заметны.

<b>Шаг 6 — Смотри NFL и разбирай игры</b>
Лучший способ понять тактику — смотреть профессиональные матчи с пониманием что происходит.

<b>💡 Важно знать:</b>
• Возраст не важен — играют от 16 до 45+ лет
• Для разных позиций нужны разные данные — найдётся место для всех
• Не нужно быть быстрым или большим — важна голова!
"""
    await callback.message.edit_text(text, reply_markup=back_kb("menu_beginners"))
    await callback.answer()


