from aiogram import Router, F
from aiogram.types import CallbackQuery

from keyboards.menus import knowledge_kb, back_kb

router = Router()


@router.callback_query(F.data == "knowledge_terms")
async def knowledge_terms(callback: CallbackQuery):
    text = """
📖 <b>Терминология американского футбола</b>

<b>Основные термины:</b>

🏈 <b>Down</b> — попытка продвинуть мяч. Команда имеет 4 попытки чтобы пройти 10 ярдов.

📏 <b>Yard (ярд)</b> — единица измерения, ~91 см. Поле 100 ярдов в длину.

🎯 <b>Touchdown (ТД)</b> — занос мяча в зачётную зону. 6 очков.

🦵 <b>Field Goal (ФГ)</b> — удар между стоек. 3 очка.

💥 <b>Sack</b> — захват квотербека за линией схватки со штрафной потерей ярдов.

🏃 <b>Snap</b> — передача мяча центром квотербеку — начало каждого розыгрыша.

📋 <b>Play</b> — разыгрываемая комбинация/схема.

🔄 <b>Turnover</b> — потеря мяча (перехват или фамбл).

🏳️ <b>Punt</b> — удар по мячу ногой при 4-м дауне для смены позиции.

⚡ <b>Blitz</b> — атака с дополнительными защитниками на квотербека.
"""
    await callback.message.edit_text(text, reply_markup=back_kb("menu_knowledge"))
    await callback.answer()


@router.callback_query(F.data == "knowledge_rules")
async def knowledge_rules(callback: CallbackQuery):
    text = """
📏 <b>Основные правила игры</b>

<b>Структура игры:</b>
• 4 четверти по 15 минут (NFL)
• Перерыв в полувремя после 2-й четверти
• Если ничья — овертайм 10 минут

<b>Как набрать очки:</b>
• 🏈 Тачдаун — 6 очков
• 🦵 Пат (удар после ТД) — 1 очко
• 💪 Двухочковая конверсия — 2 очка
• 🎯 Филд гол — 3 очка
• 🛡️ Сейфти (захват в своей зоне) — 2 очка сопернику

<b>Владение мячом:</b>
• 4 попытки (дауна) чтобы пройти 10 ярдов
• Прошёл 10 ярдов → снова 4 попытки
• Не прошёл на 4-м дауне → мяч переходит сопернику

<b>Важные правила:</b>
• За линию схватки нельзя передавать мяч вперёд более одного раза
• Принимающий должен поймать мяч двумя ногами в поле
• Нельзя атаковать квотербека после броска
"""
    await callback.message.edit_text(text, reply_markup=back_kb("menu_knowledge"))
    await callback.answer()


